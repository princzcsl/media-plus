export function iconSvg(name, size = 18) {
  return `<svg aria-hidden="true" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${PATHS[name] || ''}</svg>`;
}

// Tiny element builder: h('button', { class: 'x', onclick }, 'text', child)
export function h(tag, props = {}, ...children) {
  const el = document.createElement(tag);
  for (const [key, value] of Object.entries(props)) {
    if (value == null || value === false) continue;
    if (key === 'class') el.className = Array.isArray(value) ? value.filter(Boolean).join(' ') : value;
    else if (key === 'icon') el.insertAdjacentHTML('afterbegin', iconSvg(value, props.iconSize));
    else if (key === 'iconSize') continue;
    else if (key.startsWith('on')) el.addEventListener(key.slice(2), value);
    else if (key === 'dataset') Object.assign(el.dataset, value);
    else if (key in el && typeof value !== 'string') el[key] = value;
    else el.setAttribute(key, value === true ? '' : value);
  }
  for (const child of children.flat()) if (child != null && child !== false) el.append(child);
  return el;
}

export function setIcon(el, name, size) {
  const svg = el.querySelector('svg');
  if (el.dataset.iconName === name) return;
  el.dataset.iconName = name;
  if (svg) svg.outerHTML = iconSvg(name, size);
  else el.insertAdjacentHTML('afterbegin', iconSvg(name, size));
}

let toastTimer;
export function toast(message, kind = 'info') {
  const el = document.getElementById('toast');
  el.textContent = message;
  el.className = `toast show ${kind}`;
  clearTimeout(toastTimer);
  toastTimer = setTimeout(() => { el.className = 'toast'; }, 2600);
}

export function fmtTime(sec) {
  if (sec < 0) return 'LIVE';
  const s = Math.max(0, Math.floor(sec || 0));
  const h = Math.floor(s / 3600);
  const m = Math.floor((s % 3600) / 60);
  const r = String(s % 60).padStart(2, '0');
  return h ? `${h}:${String(m).padStart(2, '0')}:${r}` : `${m}:${r}`;
}

// Calls fn at most once per `wait` ms, always with the latest arguments.
export function throttle(fn, wait = 60) {
  let timer = null;
  let last = null;
  return (...args) => {
    last = args;
    if (timer) return;
    fn(...last);
    timer = setTimeout(() => {
      timer = null;
      if (last !== null) fn(...last);
      last = null;
    }, wait);
    last = null;
  };
}

export async function send(msg) {
  const res = await chrome.runtime.sendMessage(msg);
  if (res?.error) throw new Error(res.error);
  return res;
}
